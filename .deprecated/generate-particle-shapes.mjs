// One-off generator: rasterizes each source mark and samples its filled
// area into a normalized point cloud, so the runtime component never ships
// an icon library or does image decoding in the browser -- just reads a
// static array of {x, y} in a -50..50 shape-space. Real marks only (GitHub/
// X/Instagram from simple-icons via jsDelivr, LinkedIn from its own actual
// "in" lettering) -- never hand-drawn path data. Run with:
//   node scripts/generate-particle-shapes.mjs
import sharp from "sharp";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SRC_DIR = path.join(__dirname, "particle-sources");
const RASTER_SIZE = 160;
const STEP = 5; // sample every Nth pixel -- controls dot density/count
const ALPHA_THRESHOLD = 80;

const SHAPES = ["github", "x", "instagram", "linkedin"];

async function sampleShape(name) {
  const svg = await readFile(path.join(SRC_DIR, `${name}.svg`));
  const { data, info } = await sharp(svg)
    .resize(RASTER_SIZE, RASTER_SIZE, { fit: "contain" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const points = [];
  for (let y = 0; y < info.height; y += STEP) {
    for (let x = 0; x < info.width; x += STEP) {
      const idx = (y * info.width + x) * info.channels;
      const alpha = data[idx + 3];
      if (alpha > ALPHA_THRESHOLD) {
        points.push([x, y]);
      }
    }
  }

  // Normalize: center on centroid, scale so the shape's half-width maps to 50.
  const cx = points.reduce((s, p) => s + p[0], 0) / points.length;
  const cy = points.reduce((s, p) => s + p[1], 0) / points.length;
  const maxDist = points.reduce(
    (m, p) => Math.max(m, Math.hypot(p[0] - cx, p[1] - cy)),
    1,
  );
  const normalized = points.map(([x, y]) => [
    Number((((x - cx) / maxDist) * 50).toFixed(2)),
    Number((((y - cy) / maxDist) * 50).toFixed(2)),
  ]);

  return normalized;
}

const result = {};
for (const name of SHAPES) {
  result[name] = await sampleShape(name);
  console.log(`${name}: ${result[name].length} points`);
}

const outPath = path.join(__dirname, "..", "src", "lib", "particle-shapes.ts");
const body = `// Generated by scripts/generate-particle-shapes.mjs -- do not hand-edit.
// Each shape is a normalized point cloud in a -50..50 space (roughly centered,
// scaled to a consistent size), sampled from real source marks: GitHub/X/
// Instagram via simple-icons (jsDelivr), LinkedIn from its own "in" lettering.
export const PARTICLE_SHAPES: Record<string, readonly (readonly [number, number])[]> = ${JSON.stringify(result)};
`;
await writeFile(outPath, body);
console.log(`Wrote ${outPath}`);
